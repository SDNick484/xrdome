#!/usr/bin/env python3
"""Usage: embed_shaders.py OUT.h NAME=file ... -- emits XRD_SHADER_<NAME>, an array of
const char * (one string per source line), for glShaderSource with
XRD_SHADER_LINES(XRD_SHADER_<NAME>) strings, and XRD_SHADER_<NAME>_ES, the same
source for GLES 3.0: the first line "#version 330 core" becomes "#version 300 es",
followed by precision statements. A source whose first line is not
"#version 330 core" is an error (exit 1, the file named). One string per line
keeps every literal short of the 4095 characters C99 promises
(-Woverlength-strings)."""
import sys

VERSION = "#version 330 core"
ES_HEAD = [
    "#version 300 es",
    "precision highp float;",
    "precision highp int;",
    "precision highp sampler2D;",
]


def emit(o, name, lines):
    o.write("static const char *const %s[] = {\n" % name)
    for ln in lines:
        esc = ln.replace("\\", "\\\\").replace('"', '\\"')
        o.write('    "%s\\n",\n' % esc)
    o.write("};\n")


def main(argv):
    out = argv[1]
    shaders = []
    for arg in argv[2:]:
        name, path = arg.split("=", 1)
        with open(path) as f:
            lines = f.read().splitlines()
        if not lines or lines[0].strip() != VERSION:
            sys.stderr.write("embed_shaders: %s: first line must be '%s'\n" % (path, VERSION))
            return 1
        shaders.append((name, lines))
    with open(out, "w") as o:
        o.write("/* generated by tools/embed_shaders.py; do not edit */\n")
        o.write("#define XRD_SHADER_LINES(s) ((int)(sizeof (s) / sizeof (s)[0]))\n")
        for name, lines in shaders:
            emit(o, "XRD_SHADER_" + name, lines)
            emit(o, "XRD_SHADER_%s_ES" % name, ES_HEAD + lines[1:])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
