#!/usr/bin/env python3
"""Usage: embed_shaders.py OUT.h NAME=file ... -- emits XRD_SHADER_<NAME>, an array of
const char * (one string per source line), for glShaderSource with
XRD_SHADER_LINES(XRD_SHADER_<NAME>) strings. One string per line keeps every literal
short of the 4095 characters C99 promises (-Woverlength-strings)."""
import sys

out = sys.argv[1]
with open(out, "w") as o:
    o.write("/* generated by tools/embed_shaders.py; do not edit */\n")
    o.write("#define XRD_SHADER_LINES(s) ((int)(sizeof (s) / sizeof (s)[0]))\n")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        with open(path) as f:
            lines = f.read().splitlines()
        o.write("static const char *const XRD_SHADER_%s[] = {\n" % name)
        for ln in lines:
            esc = ln.replace("\\", "\\\\").replace('"', '\\"')
            o.write('    "%s\\n",\n' % esc)
        o.write("};\n")
