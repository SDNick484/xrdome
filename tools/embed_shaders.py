#!/usr/bin/env python3
"""Usage: embed_shaders.py OUT.h NAME=file ... -- emits const char XRD_SHADER_<NAME>[] strings."""
import sys

out = sys.argv[1]
with open(out, "w") as o:
    o.write("/* generated by tools/embed_shaders.py; do not edit */\n")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        with open(path) as f:
            lines = f.read().splitlines()
        o.write("static const char XRD_SHADER_%s[] =\n" % name)
        for ln in lines:
            esc = ln.replace("\\", "\\\\").replace('"', '\\"')
            o.write('    "%s\\n"\n' % esc)
        o.write("    ;\n")
